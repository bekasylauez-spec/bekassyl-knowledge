def offset_poly(P, d):
    lines = []
    for (r1, z1), (r2, z2) in zip(P[:-1], P[1:]):
        L = math.hypot(r2 - r1, z2 - z1); dr_, dz_ = (r2 - r1) / L, (z2 - z1) / L
        n = (dz_, -dr_)                                   # төмен-сыртқа нормаль
        lines.append(((r1 + d * n[0], z1 + d * n[1]), (dr_, dz_)))
    out = [lines[0][0]]
    for (p1, d1), (p2, d2) in zip(lines[:-1], lines[1:]):
        # p1 + t d1 = p2 + s d2
        a = np.array([[d1[0], -d2[0]], [d1[1], -d2[1]]]); b = np.array([p2[0] - p1[0], p2[1] - p1[1]])
        t, _ = np.linalg.solve(a, b)
        out.append((p1[0] + t * d1[0], p1[1] + t * d1[1]))
    (pl, (dr_, dz_)) = lines[-1]
    last = P[-1]; n = (dz_, -dr_)
    out.append((last[0] + d * n[0], last[1] + d * n[1]))
    return out


