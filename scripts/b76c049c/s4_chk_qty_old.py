def seg_z(segs, r):
    out = np.full(r.shape, np.nan)
    for ra, rb, za, zb in segs:
        m = (r >= ra) & (r < rb)
        out[m] = za + (zb - za) * (r[m] - ra) / (rb - ra)
    return out


def vol_integral(top, bot, rmax, dr=0.1):
    """1-тәсіл: V = ∫ 2π r (ztop-zbot) dr, орта нүкте, dr=0.1 мм (мм3)"""
    r = (np.arange(int(rmax / dr)) + 0.5) * dr
    T = seg_z(top, r) - seg_z(bot, r)
    assert not np.isnan(T).any(), 'профиль саңылауы'
    assert (T >= -1e-6).all(), 'теріс қалыңдық'
    return float(np.sum(2 * pi * r * T) * dr)


def tri_ring(ra, rb, T1, T2):
    dT = T2 - T1
    if dT >= 0:
        base = T1; tri = pi * (rb - ra) * dT * (ra + 2 * rb) / 3
    else:
        base = T2; tri = pi * (rb - ra) * (-dT) * (2 * ra + rb) / 3
    return pi * (rb ** 2 - ra ** 2) * base + tri


def vol_decomp(top, bot):
    """2-тәсіл: қарапайым денелерге: цилиндр-сақина (π(R²-r²)·t_min) + үшбұрышты қимасы бар конус-сақина (Паппус)"""
    br = sorted(set([s[0] for s in top] + [s[1] for s in top] + [s[0] for s in bot] + [s[1] for s in bot]))
    V = 0; parts = []
    e = 1e-7
    for a, b in zip(br[:-1], br[1:]):
        if b - a < 1e-9: continue
        ta = seg_z(top, np.array([a + e]))[0] - seg_z(bot, np.array([a + e]))[0]
        tb = seg_z(top, np.array([b - e]))[0] - seg_z(bot, np.array([b - e]))[0]
        v = tri_ring(a, b, ta, tb); V += v; parts.append((a, b, ta, tb, v))
    return V, parts


def vol_polygon(top, bot):
    """3-тәсіл (бақылау): Паппус, бүкіл қима полигоны: V = 2π·(1/6)Σ(ri+ri+1)(ri zi+1 - ri+1 zi)"""
    pts = []
    for ra, rb, za, zb in bot: pts += [(ra, za), (rb, zb)]
    for ra, rb, za, zb in reversed(top): pts += [(rb, zb), (ra, za)]
    s = 0
    for i in range(len(pts)):
        r1, z1 = pts[i]; r2, z2 = pts[(i + 1) % len(pts)]
        s += (r1 + r2) * (r1 * z2 - r2 * z1)
    return abs(2 * pi * s / 6)


def frustum(h, R, r):
    return pi * h / 3 * (R * R + R * r + r * r)


