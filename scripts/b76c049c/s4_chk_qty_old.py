def mesh(R, cutR, rflat, r0, offs):
    ys = [k * 100 + offs for k in range(-80, 81) if abs(k * 100 + offs) < R]
    pieces = 0; L2 = 0.0; L3 = 0.0
    for y in ys:
        half = math.sqrt(R * R - y * y)
        segs = [(-half, half)]
        if cutR and abs(y) < cutR:
            inn = math.sqrt(cutR ** 2 - y * y); segs = [(-half, -inn), (inn, half)]
        for a, b in segs:
            x = np.linspace(a, b, 4001); rr_ = np.hypot(x, y)
            s = np.where((rr_ >= r0) & (rr_ <= rflat), SLOPE * x / np.maximum(rr_, 1e-9), 0.0)
            L3 += float(np.trapezoid(np.sqrt(1 + s * s), x)); L2 += b - a; pieces += 1
    return len(ys), pieces, L2, L3


