import json, sys, math, re
S = sys.argv[1]
txt = open(S + '/km/s5.txt', encoding='utf-8').read().splitlines()
yB = lambda L: -1739092.2 + 1000 * L          # уровни аналога и наши в одной системе (авто-отметки СПДС)
ops = []
sw = lambda win, d: ops.append({"t": "stretchwin", "win": win, "d": d})
D4 = 12896.2                                   # сдвиг 4-4 относительно 3-3
# ---- стереть: цепочки высот, ось А + 300, линии над стойками, верхний ярус 4-4, кронштейны 4-4
ops.append({"t": "erase", "h": ["671F66", "671F73", "671F80", "671F8D", "671F9A", "671FAA", "671FB7", "671FC4", "671FD1",
    "6720C2", "6720CF", "6720DC", "6720E9", "6720F9", "672106", "672113", "672120", "6721D5",
    "671F35", "671F36", "672091", "672092", "671F61", "671F62", "6720BD", "6720BE",
    "672219", "67224C", "67224D", "67224E", "67224F", "67221A", "672247", "672248", "672249", "67221B", "672228", "672235",
    "6721C5", "6721C6", "6721C7", "67224A", "6721C8", "6721C9", "6721CA", "67224B"]})
# ---- [20П -> [18П (кромка к стойке / к зазору 100 сохраняется)
for l in txt:
    m = re.match(r'INSERT (\w+) \S+ Швеллер_№20П \S+ \S+ \S+ @([\d.]+),([-\d.]+) s([-\d.]+),', l)
    if m and m.group(1) not in ("67224C", "67224D", "67224E", "67224F"):
        x, y, s = float(m.group(2)), float(m.group(3)), float(m.group(4))
        ops.append({"t": "setblock", "h": m.group(1), "name": "Швеллер_№18П ГОСТ 8240-97_L-1_Front", "at": [x + (6 if s > 0 else -6), y]})
# ---- по горизонтали: 2500 -> 1860 между гранями стоек (пролёты 1200 -> 880)
for dx in (0, D4):
    sw([2687300 + dx, -1745000, 2695200 + dx, -1719500], [320, 0])
    sw([2697370 + dx, -1745000, 2700300 + dx, -1719500], [-320, 0])
    sw([2697550 + dx, -1745000, 2700300 + dx, -1719500], [30, 0])          # стена: кронштейн К1 230
ops.append({"t": "move", "h": ["672080", "6721C4"], "d": [-290, 0]})
# ---- по вертикали
def vsteps(dx, steps):
    for cut_lo, cut_hi, d in steps:
        sw([2687300 + dx, cut_lo, 2700300 + dx, cut_hi], [0, d])
X3, X4 = 0, D4
vsteps(X3, [(-1741500, -1719500, -5100), (-1747000, yB(-0.5), 4120), (yB(2.0), -1719500, -400), (yB(5.6), -1719500, -800), (yB(9.0), -1719500, -700)])
vsteps(X4, [(-1741500, -1719500, -1300), (-1747000, yB(0.8), 320), (yB(3.5), -1719500, -500), (yB(7.5), -1719500, -750)])
# стойки до кровли: Y=0 -> +13.700, Y=2.0 -> +13.900
for dx, top in ((X3, 10.7), (X4, 13.15)):
    sw([2695200 + dx, yB(top - 0.01), 2695370 + dx, -1719500], [0, (13.7 - top) * 1000])
    sw([2697200 + dx, yB(top - 0.01), 2697370 + dx, -1719500], [0, (13.9 - top) * 1000])
# ---- балки Б1 248 -> 140 (□140x5), кронштейны 200 -> 120
for dx, levels in ((X3, (0, 3.8, 7.2, 10.7)), (X4, (1.8, 5.5, 8.95))):
    for L in levels:
        b = yB(L) - 200 - 248
        sw([2695200 + dx, b - 5, 2697370 + dx, b + 5], [0, 108])
for L in (0, 3.8, 7.2, 10.7):
    b = yB(L) - 400
    sw([2697340, b - 5, 2697600, b + 5], [0, 80])
# ---- отметки
for h, d in (("672254", 12.08), ("671FA8", 0.3), ("671FA9", 0.25),
             ("672259", -1.3), ("672258", -1.5), ("6720F6", -1.7), ("672257", -1.75), ("6720F7", -1.75), ("672256", -2.0), ("6720F8", -2.45), ("672255", -1.45)):
    ops.append({"t": "xform", "h": h, "base": [0, 0], "to": [0, d * 1000]})
# ---- кровля Пр1 □100x4 по стропилу (уклон 10 %)
for dx in (X3, X4):
    xl, xr = 2695214.6 + dx, 2697354.6 + dx
    ops.append({"t": "pl", "p": [[xl, yB(13.7)], [xr, yB(13.9)], [xr, yB(13.9) + 100], [xl, yB(13.7) + 100]], "closed": True,
                "layer": "Размеры", "color": 256, "lw": -1})
    ops.append({"t": "note", "l1": "Пр1", "origin": [xl + 300, yB(13.7) + 900], "target": [xl + 700, yB(13.7) + 140], "scale": 100})
# ---- цепочки высот
def chain(dx, lv):
    xp = 2695214.6 + dx
    for a, b in zip(lv, lv[1:]):
        ops.append({"t": "dim", "h": "673132", "p1": [xp, yB(a)], "p2": [xp, yB(b)], "dl": [2694128 + dx, yB(b)], "rot": math.pi / 2})
    ops.append({"t": "dim", "h": "673132", "p1": [xp, yB(lv[0])], "p2": [xp, yB(lv[-1])], "dl": [2693184 + dx, yB(lv[-1])], "rot": math.pi / 2})
chain(X3, [-0.98, 0, 3.8, 7.2, 10.7, 13.7])
chain(X4, [-0.98, 1.8, 5.5, 8.95, 13.7])
# ---- узлы: 6 (Б1 на стойке аналога) -> 5, кронштейн -> 6
for h in ("672088", "6721CC"): ops.append({"t": "mcset", "h": h, "set": {"Knot": "5"}})
ops.append({"t": "noteset", "win": [2697440, -1745000, 2700300, -1719500], "from": "Л", "to": "К1"})
# ---- заголовки, штамп, примечания
ops.append({"t": "settext", "h": "671FEC", "s": "Разрез 2 - 2"}); ops.append({"t": "settext", "h": "671FEE", "s": "Разрез 3 - 3"})
ops.append({"t": "move", "h": ["671FEC", "671FEE"], "d": [0, -3800]})
ops.append({"t": "settext", "h": "671FE7", "s": "Разрезы 2 - 2; 3 - 3"})
ops.append({"t": "settext", "h": "671FEA", "s": "\pxi-3.3333,l3.3333,t3.3333;1.\tОбщие данные см. на листах 1.1, 1.2, спецификацию металлопроката - на листе 2.\P2.\tРазрез 2 - 2 - по оси стоек у площадок этажей, разрез 3 - 3 - по оси стоек у промежуточных площадок.\P3.\tУзлы 4, 5 см. на листе 7, узел 6 (кронштейн К1) - на листе 7."})
json.dump(ops, open(sys.argv[2], "w", encoding="utf-8"), ensure_ascii=False)
print(len(ops))
