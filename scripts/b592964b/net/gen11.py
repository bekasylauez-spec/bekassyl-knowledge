# лист 11: фрагменты ограждения Байтурсынова -> лестница БЦ (марш 2100 при уклоне 230/300, площадка 1860)
import json, sys
ops = []
sw = lambda win, d: ops.append({"t": "stretchwin", "win": win, "d": d})
# --- О2: правая стойка неподвижна, левая сдвигается: пролёт 11000 -> 8200 (М 1:25 = x4), подъём 8800 -> 8200*230/300
s = 230 / 300; dy = -(8800 - 8200 * s)
bal = ["67B%03X" % k for k in range(0x242, 0x259)]
ops.append({"t": "erase", "h": bal})
sw([2815000, -1736500, 2819400, -1729000], [2800, dy])
xl, xr = 2822113.5, 2830313.5
yb0 = -1734051 + dy              # верх нижнего пояса у левой стойки
yt0 = -1730107.2 + dy            # низ поручня у левой стойки
x = xl + 418.3
while x + 80 <= xr - 418:
    yb = yb0 - (x - xl) * s; yt = yt0 - (x - xl) * s
    ops.append({"t": "pl", "p": [[x, yb], [x + 80, yb - 80 * s], [x + 80, yt - 80 * s], [x, yt]], "closed": True, "layer": "0", "color": 256, "lw": -1})
    x += 458.3
# --- О10: 2050 -> 1860, правая часть влево на 760
ops.append({"t": "erase", "h": ["67B2B6"]})
sw([2843800, -1739500, 2850000, -1729000], [-760, 0])
json.dump(ops, open(sys.argv[1], "w", encoding="utf-8"), ensure_ascii=False)
print(len(ops))
