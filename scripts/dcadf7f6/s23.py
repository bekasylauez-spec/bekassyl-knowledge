"""2.3 Разрезы 1-1, 2-2"""
from common import *

A_LEV_R = '116C3A'

def levR(y_zero, at, sc=100):
    t = tag('lv'); op(t='clone', h=A_LEV_R, tag=t)
    t2 = tag('lb'); op(t='levbase', h=t, old=A_LEV_ZERO, new=y_zero, tag=t2)
    op(t='mcscale', h=t2, v=sc); op(t='moveto', h=t2, idx=0, to=list(at)); return t2


def cut(x0, z0, x1, z1, OX, OZ):
    g = box(min(x0, x1), min(z0, z1), max(x0, x1), max(z0, z1))
    outline(g, OX, OZ); hatch_geom(g, OX, OZ)


def vis(x0, z0, x1, z1, OX, OZ):
    rect(OX + x0, OZ + z0, OX + x1, OZ + z1, layer=L_THIN)


def build(X0, Y0):
    s = Sheet('2.3', 'Разрезы 1-1, 2-2', None, X0, Y0, 'A1')
    N = lambda l1, t, d, O, l2='': note(l1, l2, (O[0] + t[0] + d[0], O[1] + t[1] + d[1]), (O[0] + t[0], O[1] + t[1]))
    # ---------- 1-1 (y = 16000) ----------
    OX, OZ = X0 + 10500, Y0 + 44500
    O = (OX, OZ)
    s.text(title_u('Разрез 1-1'), OX + 22000, OZ + 9200, 300, att=8, layer='0')
    rect(OX + 5800, OZ - 4800, OX + 45200, OZ - 4700, layer=L_THIN)          # подбетонка
    cut(5900, -4700, 45100, -4000, *O)                                         # Фм-1
    for x in (6800, 37800, 44200): cut(x - 200, -4000, x + 200, 3300, *O)     # walls
    cut(6600, 3300, 44400, 3500, *O)                                           # Пм-1
    for x in (19350, 25350, 31350): cut(x - 175, 2800, x + 175, 3300, *O)
    for x in (8700, 11000, 13350, 16350, 22350, 28350, 34600, 41000): cut(x - 150, 2850, x + 150, 3300, *O)
    for x in (13350, 19350, 25350, 31350): vis(x - 250, -4000, x + 250, 2800, *O)   # Км-1 beyond
    pl([(OX + 7000, OZ + 2800), (OX + 37600, OZ + 2800)], layer=L_THIN)              # Бм-1 beyond
    # pavilion
    cut(-150, -1200, 150, -600, *O)                                            # Рб-1
    vis(-1100, -2100, 1100, -1800, *O); vis(-700, -1800, 700, -1200, *O)       # Фм-2 beyond
    rect(OX - 1200, OZ - 2200, OX + 1200, OZ - 2100, layer=L_THIN)
    vis(-250, -1200, 250, 4450, *O)                                            # Км-3 beyond
    vis(6600, 3500, 7000, 4800, *O)                                            # Км-4 beyond
    cut(-250, 4800, 6800, 4950, *O)                                            # Пм-2
    for x in (0, 6800): cut(x - 175, 4450, x + 175, 4800, *O)                  # Рм-1 cut
    pl([(OX + 250, OZ + 4450), (OX + 6600, OZ + 4450)], layer=L_THIN)          # Рм-1 beyond (y=19170)
    for k, x in AX.items(): axis(k, (OX + x, OZ + 5600), (OX + x, OZ - 7800), 100, True)
    xs = sorted(AX.values())
    chain_h([OX + x for x in [-250, 0, 5900, 6800] + xs[2:] + [45100]], OZ - 4800, OZ - 5700)
    chain_h([OX + x for x in xs], OZ - 4800, OZ - 6500)
    chain_v([OZ + z for z in (-4800, -4700, -4000, 3300, 3500)], OX + 45100, OX + 46400)
    chain_v([OZ + z for z in (-2100, -1200, 4450, 4950)], OX - 1200, OX - 1900)
    for z in (-4700, -4000, 3500): lev(OZ, (OX + 5300, OZ + z))
    for z in (-2100, -1200, 4950): lev(OZ, (OX - 3000, OZ + z))
    N('Фм-1', (24000, -4000), (400, 400), O); N('См-1', (7000, -1000), (400, 400), O); N('См-1', (44000, -1000), (-1400, 400), O)
    N('См-2', (38000, -1000), (400, 400), O); N('Пм-1', (24000, 3500), (400, 400), O); N('Пм-2', (3400, 4950), (400, 400), O)
    N('Бм-1', (19525, 2900), (400, -500), O); N('Бм-2', (16500, 2900), (400, -500), O); N('Км-1', (13600, 0), (400, 400), O)
    N('Км-3', (250, 2000), (400, 400), O); N('Рм-1', (2000, 4450), (400, -500), O); N('Км-4', (7000, 4200), (400, 300), O); N('Рб-1', (150, -900), (400, 400), O)
    N('Фм-2', (1100, -1900), (400, -500), O)
    N('Бетонная подготовка', (30000, -4800), (400, -500), O, 'C8/10 t=100')
    # ---------- 2-2 (x = 22000) ----------
    OX, OZ = X0 + 10500, Y0 + 20500
    O = (OX, OZ)
    s.text(title_u('Разрез 2-2'), OX + 12350, OZ + 6800, 300, att=8, layer='0')
    rect(OX - 1000, OZ - 4800, OX + 25700, OZ - 4700, layer=L_THIN)
    cut(-900, -4700, 25600, -4000, *O)
    for y in (0, 12350, 24700): cut(y - 200, -4000, y + 200, 3300, *O)
    cut(-200, 3300, 24900, 3500, *O)
    for y in (6200, 18500): cut(y - 175, 2800, y + 175, 3300, *O)
    for y in (6200, 18500): vis(y - 250, -4000, y + 250, 2800, *O)
    pl([(OX + 200, OZ + 2850), (OX + 12150, OZ + 2850)], layer=L_THIN); pl([(OX + 12550, OZ + 2850), (OX + 24500, OZ + 2850)], layer=L_THIN)
    for k, y in AY.items(): axis(k, (OX + y, OZ + 5000), (OX + y, OZ - 7800), 100, True)
    ys = sorted(AY.values())
    chain_h([OX + y for y in [-900] + ys + [25600]], OZ - 4800, OZ - 5700)
    chain_h([OX + y for y in ys], OZ - 4800, OZ - 6500)
    chain_v([OZ + z for z in (-4800, -4700, -4000, 3300, 3500)], OX + 25600, OX + 26900)
    for z in (-4700, -4000, 2800, 3500): lev(OZ, (OX - 1500, OZ + z))
    N('Фм-1', (9000, -4000), (400, 400), O); N('См-1', (200, -1000), (400, 400), O); N('См-2', (12550, -1000), (400, 400), O)
    N('Пм-1', (9000, 3500), (400, 400), O); N('Бм-1', (6375, 2900), (400, -500), O); N('Км-1', (18750, 0), (400, 400), O)
    N('Бетонная подготовка', (16000, -4800), (400, -500), O, 'C8/10 t=100')
    s.notes(['Общие указания см. лист 1.1.', 'Разрезы читать совместно с листами 2.1, 2.2.',
             'Под фундаментами выполнить бетонную подготовку из бетона C8/10 толщиной 100 мм.',
             'Наружные поверхности, соприкасающиеся с грунтом, обмазать горячим битумом за 2 раза.',
             'Рабочий шов бетонирования плита Фм-1 / стены - с гидрошпонкой.'], x=X0 + 65100, y=Y0 + 6462)
    return s
