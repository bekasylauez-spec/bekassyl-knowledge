"""5.1 Стены См-1, См-2 (1:25, A1)"""
import math
from common import *

SC = 25
L_OUT = 2 * (37400 + 24700)                                   # 124200
L_IN = 3700 + 15500 + 4 * 6400 + 2 * 1900 + 29100            # 77700
LW = L_OUT + L_IN
H = 7300


def brk_h(x0, x1, z):
    xm = (x0 + x1) / 2
    pl([(x0 - 60, z), (xm - 60, z), (xm - 20, z + 40), (xm + 20, z - 40), (xm + 60, z), (x1 + 60, z)], layer=L_THIN)


def brk_v(x, z0, z1):
    zm = (z0 + z1) / 2
    pl([(x, z0 - 60), (x, zm - 60), (x - 40, zm - 20), (x + 40, zm + 20), (x, zm + 60), (x, z1 + 60)], layer=L_THIN)


def wall_section(OX, OZ):
    X = lambda x: OX + x; Z = lambda z: OZ + z
    # wall x 0..400 ; slab Фм-1 below (-4700..-4000), Пм-1 above (3300..3500)
    pl([(X(-1300), Z(-4700)), (X(1700), Z(-4700))]); pl([(X(-1300), Z(-4000)), (X(0), Z(-4000)), (X(0), Z(3300)), (X(-1300), Z(3300))])
    pl([(X(1700), Z(-4000)), (X(400), Z(-4000)), (X(400), Z(3300)), (X(1700), Z(3300))])
    pl([(X(-1300), Z(3500)), (X(1700), Z(3500))])
    for x in (-1300, 1700): brk_v(X(x), Z(-4700), Z(-4000)); brk_v(X(x), Z(3300), Z(3500))
    zb, zt = -4640, -4050
    rbar([(X(-1300), Z(zb)), (X(1700), Z(zb))]); rbar([(X(-1300), Z(zt)), (X(1700), Z(zt))])
    # dowels Вп-1 (from Фм-1) and vertical поз.1 both faces
    for xv, sg in ((50 + 16 + 10, -1), (400 - 76, 1)):
        rbar([(X(xv + sg * 200), Z(zb + 45)), (X(xv), Z(zb + 45)), (X(xv), Z(-4000 + 1220))])
        xb = xv - sg * 22
        rbar([(X(xb), Z(-4000 + 50)), (X(xb), Z(3500 - 40 - 12)), (X(xb + sg * 500), Z(3500 - 40 - 12))])
        # доп. поз.2 (lower zone 3000) shown offset
        rbar([(X(xb - sg * 22), Z(-4000 + 50)), (X(xb - sg * 22), Z(-1000))])
    # horizontal поз.3 dots (outside verticals)
    zs = [-4000 + 100 + 200 * i for i in range(int((H - 100) / 200) + 1)]
    rdots([(X(50 + 8), Z(z)) for z in zs], 16); rdots([(X(400 - 58), Z(z)) for z in zs], 16)
    # шпильки поз.4 every 400 (shown every other level)
    for z in zs[::2]: pl([(X(40), Z(z + 20)), (X(360), Z(z + 20))], layer=LRB[8], lw=40)
    # Пм-1 mesh fragment
    rbar([(X(-1300), Z(3300 + 30 + 6)), (X(1700), Z(3300 + 30 + 6))], 12); rbar([(X(-1300), Z(3500 - 30 - 6)), (X(1700), Z(3500 - 30 - 6))], 12)
    chain_v([Z(z) for z in (-4700, -4000, -1000, 3300, 3500)], X(1700), X(2200), SC, texts=['700', '3000', '4300', '200'])
    chain_h([X(0), X(200), X(400)], Z(-4700), Z(-5100), SC)
    axis('2', (X(200), Z(4300)), (X(200), Z(-5900)), SC, True)
    for z in (-4700, -4000, 3500): lev(OZ, (X(-1400), Z(z)), SC)
    note('1', 'ш.200', (X(400 + 250), Z(1300)), (X(400 - 98), Z(1000)), SC)
    note('2', 'ш.200', (X(400 + 250), Z(-2200)), (X(400 - 120), Z(-2500)), SC)
    note('3', 'ш.200', (X(-750), Z(0 + 150)), (X(58), Z(-100 + 0)), SC)
    note('4', 'ш.400х400', (X(-750), Z(-3200)), (X(40), Z(-3480)), SC)
    note('Вп-1', 'ш.200', (X(-750), Z(-3600)), (X(76), Z(-3700)), SC)
    note('См-1', '', (X(-750), Z(1800)), (X(0), Z(1500)), SC)
    op(t='mtext', at=[X(200), Z(4700)], h=87.5, att=8, s='{\\L1-1}', style='Isocpeur', layer='0')


def corner_plan(OX, OY):
    """угол наружных стен (план), Г-образные поз.5 ; local: wall along X (y 0..400) and along Y (x 0..400)"""
    X = lambda x: OX + x; Y = lambda y: OY + y
    pl([(X(2000), Y(0)), (X(0), Y(0)), (X(0), Y(2000))]); pl([(X(2000), Y(400)), (X(400), Y(400)), (X(400), Y(2000))])
    brk_v(X(2000), Y(0), Y(400)); brk_h(X(0), X(400), Y(2000))
    hatch_geom(box(0, 0, 2000, 400).union(box(0, 0, 400, 2000)), OX, OY)
    a, b = 58, 342
    rbar([(X(a), Y(2000)), (X(a), Y(a)), (X(2000), Y(a))], 16)              # outer face horizontal bars
    rbar([(X(b), Y(2000)), (X(b), Y(b)), (X(2000), Y(b))], 16)
    rbar([(X(a + 25), Y(1000 + a)), (X(a + 25), Y(a + 25)), (X(1000 + a), Y(a + 25))], 16)   # поз.5 Г 1000+1000
    rbar([(X(b - 25), Y(1000 + b)), (X(b - 25), Y(b - 25)), (X(1000 + b), Y(b - 25))], 16)
    vx = [76 + 200 * i for i in range(10)]
    rdots([(X(x), Y(76)) for x in vx if x < 1950] + [(X(x), Y(324)) for x in vx if 324 < x < 1950], 20)
    rdots([(X(76), Y(y)) for y in vx[1:] if y < 1950] + [(X(324), Y(y)) for y in vx[2:] if y < 1950], 20)
    note('5', 'ш.200', (X(1200), Y(-300)), (X(900), Y(a + 25)), SC)
    note('3', '', (X(1600), Y(-300)), (X(1400), Y(a)), SC)
    chain_h([X(0), X(400)], Y(2000), Y(2350), SC); chain_v([Y(0), Y(400)], X(2000), X(2350), SC)
    op(t='mtext', at=[X(1000), Y(2600)], h=87.5, att=8, s='{\\LУгол наружных стен (план)}', style='Isocpeur', layer='0')


def build(X0, Y0):
    s = Sheet('5.1', 'Стены См-1, См-2', None, X0, Y0, 'A1', SC)
    wall_section(X0 + 3500, Y0 + 9500)
    corner_plan(X0 + 8000, Y0 + 9000)
    nv = int(round(LW / 200.0))                       # per face
    nh = 2 * (int((H - 100) / 200) + 1)
    rows = [rowL('1', 20, 7300 + 460, 2 * nv), rowL('2', 20, 3000, 2 * nv), rowPM('3', 16, round(nh * LW / 1000.0 * 1.08, 1)),
            rowL('4', 8, 520, int(LW * H / 160000.0), 'A240'), rowL('5', 16, 2000, 18 * (nh // 2) * 2)]
    tot, hh = spec_table(X0 + 21025 - 125 - 4625, Y0 + 14850 - 500, SC, 'Спецификация арматуры стен См-1, См-2 (на все стены)', rows)
    s.notes(['Общие указания см. лист 1.1. Схему расположения стен см. лист 2.1.',
             'Стены См-1 (наружные) и См-2 (внутренние) толщиной 400 мм армировать одинаково; бетон C30/37 W8 F200.',
             'Поз. 1 - вертикальная %%C20 ш.200 у обеих граней, стык с выпусками Вп-1 внахлестку 1220 мм, верх - анкеровка отгибом 500 мм в плиту Пм-1.',
             'Поз. 2 - дополнительная вертикальная %%C20 ш.200 у обеих граней в нижней зоне (3000 мм от верха Фм-1), между стержнями поз. 1.',
             'Поз. 3 - горизонтальная %%C16 ш.200 у обеих граней (снаружи вертикальной), стыки 61d вразбежку; на углах и примыканиях - поз. 5.',
             'Поз. 4 - шпильки %%C8 A240 ш.400х400 в шахматном порядке. Защитный слой 50 мм.',
             'Рабочие швы бетонирования - с гидрошпонкой. Общая масса арматуры стен %.1f кг.' % tot],
            x=X0 + 21025 - 125 - 4625, y=Y0 + 125 + 1375 + 115, w=4625)
    return s
