# -*- coding: utf-8 -*-
"""2.1 Схема расположения элементов на отм. -4.000, -1.200"""
from common import *

def build(X0, Y0):
    s = Sheet('2.1', 'Схема расположения элементов\\Pна отм. -4.000, -1.200', 'Схема расположения элементов на отм. -4.000, -1.200', X0, Y0, 'A1')
    PX, PY = X0 + 9500, Y0 + 15000
    ch = lambda xs, ye, yd: chain_h([PX + x for x in xs], PY + ye, PY + yd)
    cv = lambda ys, xe, xd: chain_v([PY + y for y in ys], PX + xe, PX + xd)
    # Фм-1 contour
    rect(PX + FM1[0], PY + FM1[1], PX + FM1[2], PY + FM1[3], layer=L_CONT)
    # walls + pilasters + columns
    pil = [col_sq(c) for c in COLS_PIL]
    cin = [col_sq(c) for c in COLS_IN]
    W = walls_geom()
    outline(unary_union(W + pil), PX, PY)
    for g in wall_pieces(pil): hatch_geom(g, PX, PY)
    for c in pil + cin:
        outline(c, PX, PY); hatch_geom(c, PX, PY)
    # pavilion: footings Фм-2, columns Км-3, rand beams Рб-1
    for (x, y) in FM2:
        rect(PX + x - 1100, PY + y - 1100, PX + x + 1100, PY + y + 1100)
        rect(PX + x - 700, PY + y - 700, PX + x + 700, PY + y + 700)
        c = col_sq((x, y)); outline(c, PX, PY); hatch_geom(c, PX, PY)
    up = unary_union([box(x - 700, y - 700, x + 700, y + 700) for x, y in FM2] + [box(6600, -200, 7000, 24900)])
    for b in RB1:
        g = box(*bar_rect(b, 300)).difference(up)
        outline(g, PX, PY)
    # axes
    axes(PX, PY, AX, AY, -4600, 46200, -4600, 26600)
    # dims bottom
    ch([-1100, 0, 5900, 6800, 13350, 19350, 25350, 31350, 37800, 44200, 45100], -1100, -2000)
    xs = sorted(AX.values())
    ch([x for x in xs], -1100, -2800)
    ch([0, 44200], -1100, -3600)
    # dims left
    ys = sorted(AY.values())
    cv([-900] + ys + [25600], -1100, -2000)
    cv(ys, -1100, -2800)
    cv([0, 24700], -1100, -3600)
    # right compartment walls
    cv([0, 4600, 10950, 13750, 20100, 24700], +45100, +46600)
    # top: partitions
    ch([6800, 8700, 37800, 44200], +25600, +27100)
    # left chamber walls
    cv([10500, 12350, 14200], +8700, +9900)
    # wall thickness
    ch([44000, 44400], +2300, +2900)
    ch([37600, 38000], +8000, +8600)
    cv([-200, 200], +16000, +16700)
    cv([12150, 12550], +23000, +23700)
    # marks
    N = lambda l1, t, d=(400, 400), l2='': note(l1, l2, (PX + t[0] + d[0], PY + t[1] + d[1]), (PX + t[0], PY + t[1]))
    N('Фм-1', (22000, 2500))
    N('См-1', (10000, 200)); N('См-1', (10000, 24500), (400, -400)); N('См-1', (44400, 7000)); N('См-1', (7000, 2500))
    N('См-2', (38000, 6000)); N('См-2', (20000, 12550)); N('См-2', (8900, 16000)); N('См-2', (7700, 10300), (400, -400))
    N('См-2', (7700, 14400), (400, 400))
    for y in (4800, 11150, 13950, 20300): N('См-2', (42000, y))
    for (x, y) in COLS_IN: N('Км-1', (x + 250, y + 250))
    for (x, y) in COLS_PIL: N('Км-2', (x + 250, y - 250) if y in (13810, 24700) else (x + 250, y + 250), (400, -400) if y in (13810, 24700) else (400, 400))
    for (x, y) in COLS_PAV: N('Км-3', (x + 250, y + 250) if y < 24000 else (x + 250, y - 250), (400, 400) if y < 24000 else (400, -400))
    for (x, y) in FM2: N('Фм-2', (x + 1100, y - 800) if y < 24000 else (x + 1100, y + 800), (400, -400) if y < 24000 else (400, 400))
    for y in PIL_Y: N('Рб-1', (3400, y + 150) if y < 24000 else (3400, y - 150), (400, 400) if y < 24000 else (400, -400))
    N('Рб-2', (150, 3000)); N('Рб-3', (150, 16500))
    plev('-4,000', (PX + 24000, PY + 9000))
    plev('-1,200', (PX + 2600, PY + 9800))
    section('1', (PX - 5600, PY + 16000), (PX + 48200, PY + 16000))
    section('2', (PX + 22000, PY + 28600), (PX + 22000, PY - 5600))
    # spec of elements
    tb = tag('tb')
    op(t='clone', h=A_TABLE, base=[10700, 356330], to=[X0 + 65100, Y0 + 56000], tag=tb)
    op(t='trows', h=tb, mode='ins', at=12, **{'from': 11}, n=4)
    rows = [(0, 0, '{\\C256;Спецификация элементов на отм. -4.000, -1.200}'),
            (2, 2, 'Фундаменты:'), (3, 0, 'Фм-1'), (3, 1, 'лист 3.1'), (3, 2, 'Плита днища Фм-1'), (3, 10, '1'),
            (4, 0, 'Фм-2'), (4, 1, 'лист 8.1'), (4, 2, 'Фундамент столбчатый Фм-2'), (4, 10, '5'),
            (5, 2, 'Стены:'), (6, 0, 'См-1'), (6, 1, 'лист 5.1'), (6, 2, 'Стена наружная См-1'), (6, 10, '1'),
            (7, 0, 'См-2'), (7, 1, 'лист 5.1'), (7, 2, 'Стена внутренняя См-2'), (7, 10, '1'),
            (8, 2, 'Колонны:'), (9, 0, 'Км-1'), (9, 1, 'лист 4.1'), (9, 2, 'Колонна Км-1'), (9, 10, '8'),
            (10, 0, 'Км-2'), (10, 1, 'лист 4.2'), (10, 2, 'Колонна Км-2 (пилястра)'), (10, 10, '5'),
            (11, 0, 'Км-3'), (11, 1, 'лист 4.3'), (11, 2, 'Колонна Км-3'), (11, 10, '5'),
            (12, 0, ''), (12, 1, ''), (12, 2, 'Балки:'), (12, 10, ''),
            (13, 0, 'Рб-1'), (13, 1, 'лист 6.11'), (13, 2, 'Рандбалка Рб-1'), (13, 10, '5'),
            (14, 0, 'Рб-2'), (14, 1, 'лист 6.12'), (14, 2, 'Рандбалка Рб-2'), (14, 10, '1'),
            (15, 0, 'Рб-3'), (15, 1, 'лист 6.13'), (15, 2, 'Рандбалка Рб-3'), (15, 10, '1')]
    op(t='tset', h=tb, cells=[[r, c, v] for r, c, v in rows])
    s.notes(['Общие указания см. лист 1.1.', 'Данный лист читать совместно с листами 2.2, 2.3.',
             'За отн. отм. 0.000 принят уровень чистого пола павильона; отметки плит даны по верху.',
             'Стены толщиной 400 мм, привязка к осям 200|200, если не указано иное.'], x=X0 + 65100, y=Y0 + 6462)
    return s
