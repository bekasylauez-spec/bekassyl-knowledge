def mesh(Rout, Rh, off):
    tot = 0
    n = 0
    for _ in range(2):
        ys = [off + 100 * k for k in range(-140, 141) if abs(off + 100 * k) < Rout]
        for y in ys:
            h = sqrt(Rout**2 - y**2)
            if abs(y) < Rh:
                x0 = sqrt(Rh**2 - y**2)
                segs = [h - x0, h - x0]
            else:
                segs = [2 * h]
            for l in segs:
                nb, t = open_run(l, 1100)
                n += nb
                tot += t * SL
    return n, tot


