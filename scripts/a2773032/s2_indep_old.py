def cam_mesh(uo, vo):
    tot = 0
    n = 0
    for k in range(-200, 200):
        u = uo + 100 * k
        if u < u0 or u > u1:
            continue
        L = vT - sqrt(Rr**2 - u**2) + 800
        nb, t = open_run(L, 1100)
        n += nb
        tot += t
    for k in range(0, 400):
        v = vo + 100 * k
        if v <= 0 or v > vT:
            continue
        if v >= Rr:
            iv = [(u0, u1)]
        else:
            s = sqrt(Rr**2 - v**2)
            iv = [(u0, min(-s, u1)), (max(s, u0), u1)]
        for a_, b_ in iv:
            if b_ - a_ <= 0:
                continue
            nb, t = open_run(b_ - a_ + 800, 1100)
            n += nb
            tot += t
    return n, tot


