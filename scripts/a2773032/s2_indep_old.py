def pappus(poly):
    s = 0
    for (x0, y0), (x1_, y1_) in zip(poly, poly[1:] + poly[:1]):
        s += (x0 * y1_ - x1_ * y0) * (x0 + x1_)
    return abs(pi / 3 * s) / 1e9


