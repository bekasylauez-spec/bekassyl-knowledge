SL = sqrt(1 + 1/144)


def cl(x):
    return int(ceil(x - 1e-9))


def open_run(l, lap):
    """open bar run, splice with lap if > MAXL -> (pieces, total length)"""
    if l <= MAXL:
        return 1, l
    nb = cl((l - lap) / (MAXL - lap))
    return nb, l + (nb - 1) * lap


def ring(C, lap, mode='A'):
    k = cl(C / (MAXL - lap))
    if mode == 'A':
        return k, C + k * lap
    return k, (C + (k * lap if C > MAXL else 0))


