def slope_rings(r1, r2, sl, lap=1100, mode='A'):
    n = cl(sl / 100) + 1
    t = 0
    nb = 0
    for k in range(n):
        r = r1 + (r2 - r1) * k / (n - 1)
        kk, tt = ring(2 * pi * r, lap, mode)
        t += tt
        nb += kk
    return n, nb, t


