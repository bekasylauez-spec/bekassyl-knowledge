def fmt(v, n=2):
    return ('%.*f' % (n, v)).replace('.', ',')


def find(o, cls, X0, x, y, tol=600):
    """bbox-тың сол-төменгі бұрышы (x, y) маңындағы объект handle-ы"""
    best = None
    for p in o['ents']:
        if p[1] != cls or p[0] != 'L': continue
        e = [float(v) for v in p[4][1:].split(',')]
        d = abs(e[0] - X0 - x) + abs(e[1] - L.ROW_Y - y)
        if d < tol and (best is None or d < best[0]): best = (d, p[2])
    if best is None: raise Exception('not found %s %s %s' % (cls, x, y))
    return best[1]


def win(slot, x0, y0, x1, y1):
    X0 = L.SHEETX[slot]
    return [X0 + x0, L.ROW_Y + y0, X0 + x1, L.ROW_Y + y1]


