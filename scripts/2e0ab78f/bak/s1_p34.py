"""3.4 Спецификация фундамента Фм-1. Ведомость расхода стали. Ведомость деталей."""
import s1_lib as L, s1_qty as Q

NOTES = ['Общие указания см. л. 1.1.',
         'Стыки рабочей арматуры внахлестку без сварки, на скрутках из вязальной проволоки не менее 3 шт. на стык. Длина нахлеста 61d. Стыки располагать вразбежку, чтобы площадь рабочей арматуры, стыкуемой в одном сечении, не превышала 50%.',
         'Расход арматуры в погонных метрах приведен с учетом нахлеста.',
         'Стержни, указанные в "Ведомости деталей", должны гнуться механическим способом в холодном состоянии с радиусом гиба 4d - 6d, где d - диаметр стержня.']


def build():
    sh = L.Sheet('3.4', 'Спецификация фундамента Фм-1')
    rows = Q.Q['Фм-1']
    V = Q.V
    mats = [L.BETON + (V['Фм-1'],), L.PODG + (V['Подготовка Фм-1'],), ('ГОСТ 7473-2010', 'Бетон С12/15 (заполнение приямка), м³', V['Заполнение приямка'])]
    x = sh.X0 + 58900 - 18500
    tb, yb = L.spec(x, sh.Y0 + 41500, 'Фундамент Фм-1', rows, mats, bent=('3', '5', '6'))
    L.steel(sh.X0 + 58900 - 24584, yb - 1500, 'Фундамент Фм-1', rows)
    L.details(sh.X0 + 4000, sh.Y0 + 39000, [
        ('3', [(500, 0, '500'), (760, 1700, '1850'), (1100, -90, '1100')], ''),
        ('5', [(1100, 0, '1100'), (0, -420, '420'), (-1100, 0, '1100')], ''),
        ('6', [(650, 0, '650'), (500, 500, '710'), (0, 650, '650')], '')])
    sh.notes(NOTES)
    return sh


if __name__ == '__main__':
    import s1_run
    s1_run.go(build, 'p34')
