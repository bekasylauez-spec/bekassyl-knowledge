def shade(cell, hexcolor):
    tcPr = cell._element.get_or_add_tcPr()
    sh = OxmlElement("w:shd"); sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), hexcolor)
    tcPr.append(sh)


def table(rows, widths, header_rows=1, size=10, caption=None, align_first_left=True):
    if caption:
        para(caption, "Normal", keep=True)
    t = D.add_table(rows=len(rows), cols=len(widths))
    t.style = D.styles["Table Grid"]
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            c = t.cell(i, j); c.width = Cm(widths[j])
            c.text = ""
            p = c.paragraphs[0]
            r = p.add_run(str(val)); r.font.size = Pt(size)
            r.bold = i < header_rows
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT if (j == 0 and align_first_left and i >= header_rows) else WD_ALIGN_PARAGRAPH.CENTER
            if i < header_rows:
                shade(c, "E7ECF5")
    para("")
    return t


def merge_row(t, i, a, b):
    c = t.cell(i, a).merge(t.cell(i, b))
    for p in c.paragraphs[1:]:
        if not p.text.strip():
            p._element.getparent().remove(p._element)


