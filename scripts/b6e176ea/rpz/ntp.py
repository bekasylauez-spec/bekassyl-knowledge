def set_text(p, text):
    runs = p.runs
    if not runs:
        p.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r._element.getparent().remove(r._element)


def apply(path):
    d = docx.Document(path)
    n = 0
    for p in list(d.paragraphs):
        t = p.text
        for a, b in PARA:
            if t.startswith(a):
                if a.startswith("5. Отчет"):
                    set_text(p, "7." + t[2:]); n += 1
                elif a.startswith("6. Отчет"):
                    set_text(p, "8." + t[2:]); n += 1
                elif a.startswith("4. СП РК 2.03"):
                    set_text(p, b); n += 1
                    anchor = p
                    for ref in NEW_REFS:
                        e = copy.deepcopy(anchor._element)
                        anchor._element.addnext(e)
                        anchor = docx.text.paragraph.Paragraph(e, anchor._parent)
                        set_text(anchor, ref)
                else:
                    set_text(p, b); n += 1
                break
        for a, b in SUBS:
            if a in p.text:
                set_text(p, p.text.replace(a, b)); n += 1
        if p.text.startswith("Характеристическое значение снеговых нагрузок на грунт sk"):
            pass
    for t in d.tables:
        first = t.cell(0, 0).text.strip()
        if first == "Параметр" and len(t.rows) == len(SEIS) and "Коэффициент поведения" in t.cell(1, 0).text + t.cell(5, 0).text:
            for i, row in enumerate(SEIS):
                for j, v in enumerate(row):
                    c = t.cell(i, j)
                    set_text(c.paragraphs[0], v)
                    for r in c.paragraphs[0].runs:
                        r.font.size = Pt(10); r.bold = (i == 0)
            n += 1
        for row in t.rows:
            c = row.cells[0]
            if c.text.startswith("Характеристическое значение снеговых нагрузок на грунт sk"):
                set_text(c.paragraphs[0], "Характеристическое значение снеговых нагрузок на грунт sk (кПа), "
                                          "снеговой район II по НТП РК 01-01-3.1(4.1)-2017 [6]")
                for r in c.paragraphs[0].runs:
                    r.font.size = Pt(10)
                n += 1
    left = [p.text for p in d.paragraphs if "2.03-30" in p.text]
    left += [c.text for t in d.tables for r in t.rows for c in r.cells if "2.03-30" in c.text]
    d.save(path)
    return n, left


if __name__ == "__main__":
    for f in sys.argv[1:]:
        n, left = apply(f)
        print(f, "changes", n, "left 2.03-30:", left[:3])
