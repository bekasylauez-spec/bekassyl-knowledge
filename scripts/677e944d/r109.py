def rw(p, fn):
    s = open(p, encoding="utf-8").read()
    nl = "\r\n" if "\r\n" in s else "\n"
    s0 = s.replace("\r\n", "\n"); s2 = fn(s0)
    assert s2 != s0, p
    open(p, "w", encoding="utf-8", newline="").write(s2.replace("\n", nl))

