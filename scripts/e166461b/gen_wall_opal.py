# Wall См-1 — sheet 5.1 «Опалубочный чертеж»: piece dims (elevation + plan 1-1), plan pieces, axis 2/1 out, title / sheet no / notes.
import gx
SX, SY = 830000.0, 455939.0
def W(x, y): return [SX + x, SY + y]
ops = []
def add(**k): ops.append(k)
# dims: (handle, which point to move (1|2), new x) for elevation row (y 15147) and plan row (y 5577)
MOVE = [('11C47D', 2, 11035), ('11C4B5', 1, 15685), ('11C4A8', 2, 17535), ('11C509', 1, 22135), ('11C4FC', 2, 23985), ('11C516', 1, 28635),
        ('11C544', 2, 11035), ('11C57C', 1, 15685), ('11C56F', 2, 17535), ('11C5D0', 1, 22135), ('11C5C3', 2, 23985), ('11C5DD', 1, 28635)]
OLD = {'11C47D': (9935, 10810), '11C4B5': (15710, 16485), '11C4A8': (16735, 17510), '11C509': (22160, 22935), '11C4FC': (23185, 23960), '11C516': (28860, 29735),
       '11C544': (9935, 10810), '11C57C': (15710, 16485), '11C56F': (16735, 17510), '11C5D0': (22160, 22935), '11C5C3': (23185, 23960), '11C5DD': (28860, 29735)}
for h, which, nx in MOVE:
    a, b = OLD[h]; y = 15147 if h < '11C530' else 5577
    p1 = [nx if which == 1 else a, y]; p2 = [nx if which == 2 else b, y]
    add(t='dimpts', h=h, p1=W(*p1), p2=W(*p2))
add(t='erase', h=['11C4C2', '11C4D1', '11C589', '11C598', '11C46B', '11C41E', '11C5FE'])
# plan pieces
PL = {'11C46A': (9935, 11035), '11C469': (15685, 16485), '11C468': (16735, 17535), '11C5FD': (22135, 22935), '11C5FC': (23185, 23985), '11C467': (28635, 29735)}
loops = []
for h, (a, b) in PL.items():
    add(t='spmove', h=h, items=[[0, SX + a, SY + 5827], [1, SX + b, SY + 5827], [2, SX + b, SY + 5577], [3, SX + a, SY + 5577]])
    loops.append([W(a, 5577), W(b, 5577), W(b, 5827), W(a, 5827)])
add(t='hatch', pat='ANSI36', sc=25, ang=0, layer='.', loops=loops)
# texts
add(t='settext', h='11C183', s='{\\LОпалубочный чертеж монолитной стены по оси А/1 стена См-1 (тол.250мм)}')
add(t='settext', h='11C3E1', s='5.1')
add(t='settext', h='11C3E6', s='Опалубочный чертеж монолитной стены по оси А/1 стена См-1 (тол.250мм)')
add(t='settext', h='11C3E4', s='1. Общие указания см. л. - 1.1\\P2. Данный лист читать совместно с л. КЖ-5.2 ... 5.4\\P3. Стыки рабочей арматуры Ø≤18 - внахлестку без сварки, длина нахлеста 61d (по большему диаметру); Ø≥20 - накладками (ГОСТ 14098, С21-Рн). Стыки располагать вразбежку.\\P4. Расход арматуры в погонных метрах приведен с учетом нахлеста.')
add(t='mcset', h='11C419', set={'Word': 'А/1'})
add(t='save')
print(gx.run(ops, 'w51')[-400:])
