def W(x, y): return [round(SLOT + x, 1), round(Y0 + y, 1)]


def pl(pts, layer='Размеры', lw=30, closed=False, ltype=None):
    d = {'t': 'pl', 'p': pts, 'layer': layer, 'lw': lw, 'closed': closed, 'tag': tag()}
