"""КМ of «Помещение обезвоживания» (as in LIRA): steel roof over axes 1-6 and crane runway.
Б1  — стропильная балка, сварной двутавр 250х10 / 480х8 (h=500), по осям 1...6, А→Б→В, уклон 0.6/6.0 (верх колонн А,В +13.700, конёк +14.300).
Р1  — коньковая распорка Тр140х4.5 по оси Б (+14.300) между осями 1...6.
Пр1 — прогоны [18П по верхнему поясу Б1, 10 линий (y = 0.1 / 1.5 / 2.9 / 4.3 / 5.8 / 6.2 / 7.7 / 9.1 / 10.5 / 11.9 м), пролёты между осями.
Св1 — горизонтальные связи □120х4 (ГОСТ 30245), Св2 — □80х4: ромбическая решётка в плоскости покрытия, в каждой ячейке осей.
ПБ1 — подкрановая балка, сварной двутавр 250х10 / 300х6 (h=320), оси y=0.8 и 11.2, отм. верха консолей +11.400, пролёты 3250/4500/4500/4500/3250.
Mass with +2% welds/plates (по ТСМ). Steel С255 (Б1, ПБ1, листы), С245 (прокат)."""
import math

AX = [0, 3250, 7750, 12250, 16750, 20000]
R = 7850e-9                     # kg/mm3
def I_weld(bf, tf, hw, tw): return (2 * bf * tf + hw * tw) * R * 1000   # kg/m
KGM = {'Б1': I_weld(250, 10, 480, 8), 'ПБ1': I_weld(250, 10, 300, 6), 'Р1': 15.04, 'Пр1': 16.3, 'Св1': 14.4, 'Св2': 9.22}
PROF = {'Б1': 'Двутавр сварной 250х10/480х8', 'ПБ1': 'Двутавр сварной 250х10/300х6', 'Р1': 'Труба 140х4.5 ГОСТ 10704-91',
        'Пр1': 'Швеллер 18П ГОСТ 8240-97', 'Св1': 'Труба кв. 120х4 ГОСТ 30245-2003', 'Св2': 'Труба кв. 80х4 ГОСТ 30245-2003'}
STEEL = {'Б1': 'С255', 'ПБ1': 'С255', 'Р1': 'С245', 'Пр1': 'С245', 'Св1': 'С245', 'Св2': 'С245'}
PURL_Y = [100, 1500, 2900, 4300, 5800, 6200, 7700, 9100, 10500, 11900]


def zroof(y): return 13700 + 600 * (1 - abs(y - 6000) / 6000)


def elements():
    E = []   # (mark, length mm, qty, note)
    lb = 2 * math.hypot(6000, 600) + 2 * 150
    E.append(('Б1', round(lb), len(AX), 'оси 1...6'))
    for a, b in zip(AX, AX[1:]):
        E.append(('Р1', b - a - 300, 1, 'ось Б, %d' % (b - a)))
        E.append(('Пр1', b - a - 10, len(PURL_Y), 'пролёт %d' % (b - a)))
        dx = (b - a) / 2
        d1 = math.hypot(dx, 3000)
        E.append(('Св1', round(d1), 4, 'ячейка %d' % (b - a)))          # A side and В side (2 bars each)
        E.append(('Св2', round(d1), 4, 'ячейка %d' % (b - a)))
        E.append(('ПБ1', b - a - 20, 2, 'пролёт %d' % (b - a)))
    return E


def spec():
    tot = {}
    for mk, L, n, _ in elements():
        tot[mk] = tot.get(mk, 0) + L / 1000 * n * KGM[mk]
    return {k: v * 1.02 for k, v in tot.items()}


if __name__ == '__main__':
    for e in elements(): print(e)
    s = spec(); print({k: round(v) for k, v in s.items()}, 'total %.0f kg' % sum(s.values()))
    print({k: round(v, 1) for k, v in KGM.items()})
