def pieces(seg, cols=True):
    """split a beam line at the columns it crosses: clear spans between column faces (700 along X, 900 along Y)"""
    x0, y0, x1, y1 = seg
    if y0 == y1:   # along X
        stops = sorted(set([x0, x1] + [x for x in AX if x0 < x < x1 and y0 in AY]))
        return [(a, y0, b, y0) for a, b in zip(stops, stops[1:])]
    stops = sorted(set([y0, y1] + [y for y in AY if y0 < y < y1 and x0 in AX]))
    return [(x0, a, x0, b) for a, b in zip(stops, stops[1:])]
