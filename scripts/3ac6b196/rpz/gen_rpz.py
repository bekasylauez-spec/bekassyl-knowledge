def TABLE(data, widths=None, header=1, size=10, bold_rows=()):
    t = d.add_table(rows=len(data), cols=len(data[0])); t.style = 'Table Grid'
    body.remove(t._tbl); body.insert(len(body) - 1, t._tbl)
    for i, row in enumerate(data):
        for j, v in enumerate(row):
            c = t.cell(i, j); c.text = ''
            p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER if j else WD_ALIGN_PARAGRAPH.LEFT
            _run(p, '' if v is None else str(v), b=(i < header or i in bold_rows), size=size)
            if widths: c.width = Cm(widths[j])
    if header:
        for i in range(header):
            trPr = t.rows[i]._tr.get_or_add_trPr(); e = OxmlElement('w:tblHeader'); e.set(qn('w:val'), 'true'); trPr.append(e)
    P('', indent=False)
    return t

