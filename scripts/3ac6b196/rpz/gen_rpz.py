def trim(path):
    """убирает поля и длинные пустые полосы снимка ЛИРА (сам рисунок не меняется)"""
    im = Image.open(path).convert('RGB'); w, h = im.size; px = im.load()
    def blank_row(y): return all(sum(px[x, y]) > 735 for x in range(0, w, 3))
    def blank_col(x): return all(sum(px[x, y]) > 735 for y in range(0, h, 3))
    rows_ = [y for y in range(h) if not blank_row(y)]
    if not rows_: return path
    keep_rows = []; gap = 0
    for y in range(rows_[0], rows_[-1] + 1):
        if y in set(rows_): gap = 0; keep_rows.append(y)
        else:
            gap += 1
            if gap <= 25: keep_rows.append(y)
    cols = [x for x in range(w) if not blank_col(x)]
    x0, x1 = max(cols[0] - 8, 0), min(cols[-1] + 8, w - 1)
    out = Image.new('RGB', (x1 - x0 + 1, len(keep_rows)), 'white')
    for j, y in enumerate(keep_rows):
        out.paste(im.crop((x0, y, x1 + 1, y + 1)), (0, j))
    fn = os.path.join(TRIM_DIR, os.path.basename(path)); out.save(fn); return fn

