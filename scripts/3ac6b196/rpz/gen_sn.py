for k, w in (('A', 18.7), ('B', 72), ('C', 13), ('D', 12), ('E', 12), ('F', 13)):
    ws.column_dimensions[k].width = w
F = lambda b=False, sz=12: Font(name='ISOCPEUR', size=sz, bold=b, italic=True)
th = Side(style='thin'); BR = Border(left=th, right=th, top=th, bottom=th)
r = 2
ws.merge_cells('B2:C2'); ws['B2'] = 'Сбор нагрузок'; ws['B2'].font = F(True); ws['B2'].alignment = Alignment(horizontal='center')
r = 4

def case(label, title):
    global r
    ws.cell(r, 1, label).font = F(); c = ws.cell(r, 2, title); c.font = F(True); c.alignment = Alignment(horizontal='left'); r += 1

def text(t, b=False, sz=12):
    global r
    c = ws.cell(r, 2, t); c.font = F(b, sz); c.alignment = Alignment(horizontal='left', wrap_text=True); r += 1

def block(title, unit, rows, total='Итого ', extra=None, note=None):
    """rows: [(name, formula_or_value)], extra: [(hdr, multiplier_formula_suffix)] -> columns D.. as =C_total*k"""
    global r
    if title: text(title, True, 14)
    hdr = [('Нагрузка:', 'left'), (unit, 'center')]
    for i, (t, al) in enumerate(hdr):
        c = ws.cell(r, 2 + i, t); c.font = F(True); c.alignment = Alignment(horizontal=al); c.border = BR
    r += 1; first = r
    for i, (name, val) in enumerate(rows):
        a = ws.cell(r, 2, name); a.font = F(); a.alignment = Alignment(horizontal='left', wrap_text=True); a.border = BR
        b = ws.cell(r, 3, val); b.font = F(); b.alignment = Alignment(horizontal='center'); b.border = BR; b.number_format = '0.000'
        if extra and i == len(rows) - 1:
            for j, (h, _) in enumerate(extra):
                c = ws.cell(r, 4 + j, h); c.font = F(True); c.alignment = Alignment(horizontal='center'); c.border = BR
        r += 1
    a = ws.cell(r, 2, total); a.font = F(True); a.alignment = Alignment(horizontal='right'); a.border = BR
    b = ws.cell(r, 3, '=SUM(C%d:C%d)' % (first, r - 1)); b.font = F(True); b.alignment = Alignment(horizontal='center'); b.border = BR; b.number_format = '0.000'
    if extra:
        for j, (_, k) in enumerate(extra):
            c = ws.cell(r, 4 + j, '=C%d*%s' % (r, k)); c.font = F(True); c.alignment = Alignment(horizontal='center'); c.border = BR; c.number_format = '0.000'
    tot = r; r += 1
    if note: text(note)
    r += 1
    return tot

